#!/usr/bin/env node
/**
 * Sync vendored rendering files from the upstream obsidian-wechat-converter checkout.
 *
 * Vendor map:
 *   vendor/converter.js             <- <upstream>/converter.js                       (copy + CLI patches)
 *   vendor/apple-theme.js           <- <upstream>/themes/apple-theme.js              (esbuild IIFE bundle,
 *                                    pulls in apple-theme-config.js / apple-theme-headings.js)
 *   vendor/wechat-html-cleaner.js   <- <upstream>/services/wechat-html-cleaner.js    (esbuild CJS bundle,
 *                                    pulls in dom-utils.js / wechat-list-indent.js)
 *   vendor/heading-style-renderer.js <- <upstream>/services/heading-style-renderer.js (esbuild CJS bundle,
 *                                    pulls in custom-theme-adapter.js / theme-token-validator.js /
 *                                    engagement-card.js)
 *
 * CLI patches applied to converter.js (keep in sync with src/render.js expectations):
 *   1. `file:` added to safeProtocols — preview rendering resolves local images to file:// URLs.
 *
 * esbuild is resolved from the upstream checkout's node_modules (it is an upstream devDependency),
 * so this repo stays dependency-free for vendoring.
 *
 * Usage:
 *   node scripts/sync-vendor.mjs [--upstream D:\Code\wechat-converter]
 *   (or set WECHAT_CONVERTER_PATH)
 */

import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const cliRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const upstreamFlagIdx = args.indexOf('--upstream');
const upstreamRoot = path.resolve(
  upstreamFlagIdx !== -1 && args[upstreamFlagIdx + 1]
    ? args[upstreamFlagIdx + 1]
    : process.env.WECHAT_CONVERTER_PATH || 'D:\\Code\\wechat-converter'
);

function fail(message) {
  console.error(`[sync-vendor] ${message}`);
  process.exit(1);
}

if (!fs.existsSync(path.join(upstreamRoot, 'package.json'))) {
  fail(`upstream checkout not found: ${upstreamRoot} (pass --upstream or set WECHAT_CONVERTER_PATH)`);
}

// Pure-JS git metadata reading: the sandboxed CLI must not spawn `git` with
// piped stdio (EPERM), so .git refs are read directly instead of `git show`.
// Source files come from the upstream WORKING TREE — keep it clean and checked
// out at the commit you want to vendor before running this script.
function resolveGitDir() {
  const dotGit = path.join(upstreamRoot, '.git');
  if (!fs.existsSync(dotGit)) fail(`no .git found under ${upstreamRoot}`);
  const stat = fs.statSync(dotGit);
  if (stat.isDirectory()) return dotGit;
  const content = fs.readFileSync(dotGit, 'utf8').trim();
  if (!content.startsWith('gitdir:')) fail(`unsupported .git layout under ${upstreamRoot}`);
  const dir = content.slice('gitdir:'.length).trim();
  return path.isAbsolute(dir) ? dir : path.resolve(upstreamRoot, dir);
}

function readHeadSha(gitDir) {
  const head = fs.readFileSync(path.join(gitDir, 'HEAD'), 'utf8').trim();
  if (!head.startsWith('ref: ')) return head; // detached HEAD: already a sha
  const ref = head.slice(5).trim();
  const refPath = path.join(gitDir, ...ref.split('/'));
  if (fs.existsSync(refPath)) return fs.readFileSync(refPath, 'utf8').trim();
  const packedRefs = path.join(gitDir, 'packed-refs');
  if (fs.existsSync(packedRefs)) {
    for (const line of fs.readFileSync(packedRefs, 'utf8').split('\n')) {
      const match = line.match(/^([0-9a-f]{40})\s+(\S+)/);
      if (match && match[2] === ref) return match[1];
    }
  }
  fail(`cannot resolve git ref ${ref} under ${gitDir}`);
}

const gitDir = resolveGitDir();
const upstreamHead = readHeadSha(gitDir).slice(0, 7);
let upstreamVersion = 'unknown';
try {
  upstreamVersion = JSON.parse(fs.readFileSync(path.join(upstreamRoot, 'manifest.json'), 'utf8')).version || 'unknown';
} catch {
  /* manifest.json read failed; keep 'unknown' */
}

const bannerFor = (sourceFiles) => [
  `/*`,
  ` * Vendored from obsidian-wechat-converter @ ${upstreamHead} (v${upstreamVersion}).`,
  ` * Source: ${sourceFiles.join(', ')}`,
  ` * Generated by scripts/sync-vendor.mjs — do not edit by hand.`,
  ` */`,
].join('\n');

function loadEsbuild() {
  const requireFromUpstream = createRequire(path.join(upstreamRoot, 'package.json'));
  try {
    // eslint-disable-next-line import/no-dynamic-require
    return requireFromUpstream('esbuild');
  } catch {
    fail(`esbuild not found in ${upstreamRoot}\node_modules — run "npm install" in the upstream checkout first.`);
  }
}

async function bundle(esbuild, entry, format, outfile, sourceFiles) {
  await esbuild.build({
    entryPoints: [path.join(upstreamRoot, entry)],
    bundle: true,
    format,
    target: 'node18',
    banner: { js: bannerFor(sourceFiles) },
    outfile,
    logLevel: 'info',
    allowOverwrite: true,
  });
}

const CONVERTER_PATCHES = [
  {
    name: 'allow file: protocol (CLI previews resolve local images to file:// URLs)',
    from: "const safeProtocols = ['http:', 'https:', 'obsidian:', 'mailto:', 'tel:', 'app:', 'capacitor:'];",
    to: "const safeProtocols = ['http:', 'https:', 'obsidian:', 'mailto:', 'tel:', 'app:', 'capacitor:', 'file:'];",
  },
];

function syncConverter() {
  const raw = fs.readFileSync(path.join(upstreamRoot, 'converter.js'), 'utf8');
  let patched = raw;
  for (const patch of CONVERTER_PATCHES) {
    if (!patched.includes(patch.from)) {
      if (patched.includes(patch.to)) {
        console.log(`[sync-vendor] converter.js: patch already applied upstream — ${patch.name}`);
        continue;
      }
      fail(`converter.js: cannot apply patch (anchor not found) — ${patch.name}\nAnchor: ${patch.from}`);
    }
    patched = patched.replace(patch.from, patch.to);
    console.log(`[sync-vendor] converter.js: applied patch — ${patch.name}`);
  }
  const out = `${bannerFor(['converter.js'])}\n${patched}`;
  fs.writeFileSync(path.join(cliRoot, 'vendor', 'converter.js'), out, 'utf8');
}

async function main() {
  console.log(`[sync-vendor] upstream: ${upstreamRoot} @ ${upstreamHead} (v${upstreamVersion})`);
  const esbuild = loadEsbuild();

  syncConverter();
  await bundle(
    esbuild,
    'themes/apple-theme.js',
    'iife',
    path.join(cliRoot, 'vendor', 'apple-theme.js'),
    ['themes/apple-theme.js', 'themes/apple-theme-config.js', 'themes/apple-theme-headings.js']
  );
  await bundle(
    esbuild,
    'services/wechat-html-cleaner.js',
    'cjs',
    path.join(cliRoot, 'vendor', 'wechat-html-cleaner.js'),
    ['services/wechat-html-cleaner.js', 'services/dom-utils.js', 'services/wechat-list-indent.js']
  );
  await bundle(
    esbuild,
    'services/heading-style-renderer.js',
    'cjs',
    path.join(cliRoot, 'vendor', 'heading-style-renderer.js'),
    ['services/heading-style-renderer.js', 'services/custom-theme-adapter.js', 'services/theme-token-validator.js', 'services/engagement-card.js']
  );

  const cleaner = createRequire(path.join(cliRoot, 'package.json'))(
    path.join(cliRoot, 'vendor', 'wechat-html-cleaner.js')
  );
  if (typeof cleaner.cleanHtmlForDraft !== 'function') {
    fail('wechat-html-cleaner.js bundle does not export cleanHtmlForDraft');
  }
  const headingStyles = createRequire(path.join(cliRoot, 'package.json'))(
    path.join(cliRoot, 'vendor', 'heading-style-renderer.js')
  );
  if (typeof headingStyles.decorateArticleHeadings !== 'function' || !headingStyles.HEADING_STYLES) {
    fail('heading-style-renderer.js bundle does not export decorateArticleHeadings/HEADING_STYLES');
  }
  console.log('[sync-vendor] done: vendor/converter.js, vendor/apple-theme.js, vendor/wechat-html-cleaner.js, vendor/heading-style-renderer.js');
}

main().catch((error) => fail(error && error.stack ? error.stack : String(error)));
